-- Final Django schema for DB2. The COPROC schema must already exist.
-- Identifiers are uppercase to match the Db2 backend's identifier quoting.
-- Django applies ordinary model defaults and auto_now values in Python; this
-- script only declares database-level defaults for identity columns.

CREATE TABLE COPROC.DJANGO_MIGRATIONS (
    ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1, INCREMENT BY 1, CACHE 10 ORDER),
    APP VARCHAR(255) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    APPLIED TIMESTAMP NOT NULL,
    CONSTRAINT PK_DJANGO_MIGRATIONS PRIMARY KEY (ID)
);

CREATE TABLE COPROC.DJANGO_CONTENT_TYPE (
    ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1, INCREMENT BY 1, CACHE 10 ORDER),
    APP_LABEL VARCHAR(100) NOT NULL,
    MODEL VARCHAR(100) NOT NULL,
    CONSTRAINT PK_DJANGO_CONTENT_TYPE PRIMARY KEY (ID),
    CONSTRAINT UQ_DJANGO_CONTENT_TYPE_APP_MODEL UNIQUE (APP_LABEL, MODEL)
);

CREATE TABLE COPROC.AUTH_GROUP (
    ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1, INCREMENT BY 1, CACHE 10 ORDER),
    NAME VARCHAR(150) NOT NULL,
    CONSTRAINT PK_AUTH_GROUP PRIMARY KEY (ID),
    CONSTRAINT UQ_AUTH_GROUP_NAME UNIQUE (NAME)
);

CREATE TABLE COPROC.AUTH_PERMISSION (
    ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1, INCREMENT BY 1, CACHE 10 ORDER),
    NAME VARCHAR(255) NOT NULL,
    CONTENT_TYPE_ID INTEGER NOT NULL,
    CODENAME VARCHAR(100) NOT NULL,
    CONSTRAINT PK_AUTH_PERMISSION PRIMARY KEY (ID),
    CONSTRAINT UQ_AUTH_PERMISSION_CONTENT_CODENAME
        UNIQUE (CONTENT_TYPE_ID, CODENAME),
    CONSTRAINT FK_AUTH_PERMISSION_CONTENT_TYPE
        FOREIGN KEY (CONTENT_TYPE_ID)
        REFERENCES COPROC.DJANGO_CONTENT_TYPE (ID)
        ON DELETE CASCADE
);

CREATE TABLE COPROC.AUTH_GROUP_PERMISSIONS (
    ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1, INCREMENT BY 1, CACHE 10 ORDER),
    GROUP_ID INTEGER NOT NULL,
    PERMISSION_ID INTEGER NOT NULL,
    CONSTRAINT PK_AUTH_GROUP_PERMISSIONS PRIMARY KEY (ID),
    CONSTRAINT UQ_AUTH_GROUP_PERMISSIONS_PAIR UNIQUE (GROUP_ID, PERMISSION_ID),
    CONSTRAINT FK_AUTH_GROUP_PERMISSIONS_GROUP
        FOREIGN KEY (GROUP_ID)
        REFERENCES COPROC.AUTH_GROUP (ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_AUTH_GROUP_PERMISSIONS_PERMISSION
        FOREIGN KEY (PERMISSION_ID)
        REFERENCES COPROC.AUTH_PERMISSION (ID)
        ON DELETE CASCADE
);

CREATE TABLE COPROC.SETORES (
    ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY
